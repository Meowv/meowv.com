const copiedKey = ref('');
const feedback = ref('');
let copiedTimer: number | null = null;
let feedbackTimer: number | null = null;
let hashScrollFrame: number | null = null;

function restoreHashPosition(): void {
  const targetId = window.location.hash.slice(1);
  const categoryId = targetId.replace(/^emoji-/, '');
  if (targetId !== `emoji-${categoryId}` || !categories.some(({ id }) => id === categoryId)) {
    return;
  }

  hashScrollFrame = window.requestAnimationFrame(() => {
    document.getElementById(targetId)?.scrollIntoView({ block: 'start' });
    hashScrollFrame = null;
  });
}

function scrollToCategory(categoryId: string): void {
  const targetId = `emoji-${categoryId}`;
  document.getElementById(targetId)?.scrollIntoView({ block: 'start' });
  window.history.replaceState(window.history.state, '', `#${targetId}`);
}

async function copyEmoji(emoji: string, key: string): Promise<void> {
  try {
    await navigator.clipboard.writeText(emoji);
    copiedKey.value = key;
    feedback.value = `已复制 ${emoji}`;

    if (copiedTimer !== null) window.clearTimeout(copiedTimer);
    copiedTimer = window.setTimeout(() => {
      copiedKey.value = '';
      copiedTimer = null;
    }, 800);
  } catch {
    feedback.value = '复制失败，请手动复制';
  }

  if (feedbackTimer !== null) window.clearTimeout(feedbackTimer);
  feedbackTimer = window.setTimeout(() => {
    feedback.value = '';
    feedbackTimer = null;
  }, 1500);
}

onMounted(restoreHashPosition);

onBeforeUnmount(() => {
  if (copiedTimer !== null) window.clearTimeout(copiedTimer);
  if (feedbackTimer !== null) window.clearTimeout(feedbackTimer);
  if (hashScrollFrame !== null) window.cancelAnimationFrame(hashScrollFrame);
});
</script>

