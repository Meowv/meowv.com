export function strokeOrder(source: string): Record<string, unknown> {
  const characters = Array.from(source.trim()).filter((item) => /[\u3400-\u9fff]/.test(item));
  if (!characters.length) throw new Error('请输入汉字。');
  return {
    characters: characters.map((character) => ({
      character,
      count: strokes[character]?.length ?? null,
      order: strokes[character] ?? [],
      supported: Boolean(strokes[character]),
    })),
    note: '内置基础字表仅覆盖常用示例；未收录字符会明确标记。',
  };
}
