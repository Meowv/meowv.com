const s2t = new Map(
  Array.from(simplified, (character, index) => [character, traditional[index] ?? character]),
);
const t2s = new Map(
  Array.from(traditional, (character, index) => [character, simplified[index] ?? character]),
);
export function convertChinese(source: string, direction: 's2t' | 't2s'): string {
  const map = direction === 's2t' ? s2t : t2s;
  return Array.from(source, (character) => map.get(character) ?? character).join('');
}

