export function localTranslate(source: string): string {
  let result = source;
  const sourceHasChinese = /[\u3400-\u9fff]/.test(source);
  const pairs = phrasePairs
    .filter(([chinese]) => /[\u3400-\u9fff]/.test(chinese) === sourceHasChinese)
    .sort((a, b) => b[0].length - a[0].length);
  for (const [from, to] of pairs)
    result = result.replace(
      new RegExp(from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), sourceHasChinese ? 'g' : 'gi'),
      to,
    );
  if (result === source) throw new Error('内置离线词典暂未收录这段内容。');
  return result;
}

