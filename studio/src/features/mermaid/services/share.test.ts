import { describe, expect, it } from 'vitest';
import { deflateSync, strToU8, zlibSync } from 'fflate';
import { decodeMermaidShare, encodeMermaidShare } from './share';

function base64Url(bytes: Uint8Array): string {
  let binary = '';
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary).replaceAll('+', '-').replaceAll('/', '_').replaceAll('=', '');
}

describe('Mermaid share protocol', () => {
  it('round trips unicode source and config', () => {
    const snapshot = {
      protocol: 1 as const,
      title: '中文流程图 🐈',
      source: 'flowchart TD\n A[开始] --> B[完成]',
      configText: '{"theme":"base","fontFamily":"微软雅黑"}',
    };
    expect(decodeMermaidShare(encodeMermaidShare(snapshot))).toEqual(snapshot);
  });

  it('rejects malformed and unsupported payloads', () => {
    expect(() => decodeMermaidShare('not-a-share')).toThrow();
    const payload = encodeMermaidShare({
      protocol: 1,
      title: 'x',
      source: 'graph TD; A-->B',
      configText: '{}',
    });
    expect(() => decodeMermaidShare(payload.replace('pako:', 'pako:!'))).toThrow();
  });

  it('rejects source data that cannot fit in a share payload', () => {
    expect(() =>
      encodeMermaidShare({
        protocol: 1,
        title: '过大',
        source: 'A'.repeat(200_001),
        configText: '{}',
      }),
    ).toThrow('过大');
  });

  it('reads the official mermaid-live-editor pako state format', () => {
    const payload =
      'pako:eNpVjEFug0AMRa9iedVI4QIsKiXQZhOpXWRVyMICw4zKjEdmUFQBd--QtFLrlb_e-3_GRlrGHLtBbo0hjXApaw_pDlVh1I7R0XiFLHteThzBieevBY5PJ4HRSAjW97uHf9wkKObzpjFEY_3n-kDFvf_meYGyOlOIEq5_yeUmC7xU9t2k-f_EKKfWa9VR3lHWkEJBeldwj73aFvOoE-_RsTraIs4brTEadlxjnt6WO5qGWGPt11QL5D9E3G9TZeoNpvlhTGkKLUUuLfVKP8r6DdATXyM';
    const snapshot = decodeMermaidShare(payload);
    expect(snapshot.title).toBe('分享图表');
    expect(snapshot.source).toContain('flowchart TD');
    expect(snapshot.configText).toContain('"theme": "default"');
  });

  it('reads official plain-base64 states and retains old Studio links', () => {
    const state = JSON.stringify({
      code: 'flowchart LR\n A-->B',
      mermaid: '{"theme":"forest"}',
      grid: true,
      panZoom: true,
      rough: false,
      updateDiagram: true,
    });
    expect(decodeMermaidShare(`base64:${base64Url(strToU8(state))}`)).toMatchObject({
      source: 'flowchart LR\n A-->B',
      configText: '{"theme":"forest"}',
    });

    const legacy = JSON.stringify({
      protocol: 1,
      title: '旧链接',
      source: 'graph TD; A-->B',
      configText: '{}',
    });
    expect(decodeMermaidShare(base64Url(deflateSync(strToU8(legacy))))).toEqual({
      protocol: 1,
      title: '旧链接',
      source: 'graph TD; A-->B',
      configText: '{}',
    });
  });

  it('uses zlib-wrapped official payloads generated by the existing fflate dependency', () => {
    const state = JSON.stringify({
      code: 'graph TD; A-->B',
      mermaid: '{}',
      grid: true,
      panZoom: true,
      rough: false,
      updateDiagram: true,
    });
    expect(decodeMermaidShare(`pako:${base64Url(zlibSync(strToU8(state), { level: 9 }))}`)).toEqual(
      {
        protocol: 1,
        title: '分享图表',
        source: 'graph TD; A-->B',
        configText: '{}',
      },
    );
  });

  it('rejects a highly compressed payload whose expanded JSON exceeds the limit', () => {
    const state = JSON.stringify({ code: 'graph TD; A-->B', padding: 'x'.repeat(600_000) });
    const payload = `pako:${base64Url(zlibSync(strToU8(state), { level: 9 }))}`;
    expect(() => decodeMermaidShare(payload)).toThrow('解压后过大');
  });
});
